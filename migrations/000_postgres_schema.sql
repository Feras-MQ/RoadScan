-- RoadScan PostgreSQL schema baseline. Apply to an EMPTY, authorized PostgreSQL database.
-- Does not install extensions or migrate existing SQLite records.
BEGIN;
CREATE TABLE IF NOT EXISTS reports (
 id VARCHAR PRIMARY KEY, image_ref VARCHAR NOT NULL, image_sha VARCHAR,
 image_phash VARCHAR, created_at TIMESTAMPTZ, updated_at TIMESTAMPTZ,
 status VARCHAR, reviewer VARCHAR, source VARCHAR, source_metadata TEXT,
 latitude DOUBLE PRECISION, longitude DOUBLE PRECISION, location_source VARCHAR,
 model_version VARCHAR, inference_state VARCHAR, detections TEXT,
 score DOUBLE PRECISION, score_parts TEXT, duplicates TEXT, note TEXT
);
CREATE TABLE IF NOT EXISTS audit_events (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id VARCHAR REFERENCES reports(id), actor VARCHAR, action VARCHAR,
 details TEXT, created_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS status_history (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id VARCHAR REFERENCES reports(id), from_status VARCHAR,
 to_status VARCHAR, actor VARCHAR, created_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS ix_reports_image_sha ON reports(image_sha);
CREATE INDEX IF NOT EXISTS ix_reports_created_at ON reports(created_at);
CREATE INDEX IF NOT EXISTS ix_reports_status ON reports(status);
CREATE INDEX IF NOT EXISTS ix_reports_status_created ON reports(status,created_at);
CREATE INDEX IF NOT EXISTS ix_audit_events_report_id ON audit_events(report_id);
CREATE INDEX IF NOT EXISTS ix_status_history_report_id ON status_history(report_id);
COMMIT;
